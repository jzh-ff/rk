EXAM_LABEL = {
    '2020-11': '2020 年下半年真题',
    '2022-05': '2022 年上半年真题',
    '2022-11': '2022 年下半年真题',
    '2024-05': '2024 年上半年真题',
}

def pick_chapter(q):
    rules = CHAPTER_RULES.get(q['moduleId'], [])
    text = (q['stem'] + ' ' + ' '.join(q['options'])).lower()
    best, best_score = None, 0
    for title, kws in rules:
        score = sum(1 for kw in kws if kw in text)
        if score > best_score:
            best, best_score = title, score
    return best or DEFAULT_CHAPTER[q['moduleId']]

def guess_difficulty(q):
    text = q['stem']
    if re.search(r'计算|多少|结果|值为|地址|个数|时间为|执行时间|速率|可靠度|概率|序列|个数为|需要.*片', text):
        return 2 if len(text) < 100 else 3
    if len(text) > 110:
        return 2
    return 1

def build_explanation(q):
    label = EXAM_LABEL[q['exam']]
    ans = 'ABCD'[q['answer']]
    src = f'**来源**：{label}第 {q["no"]} 题'
    orig = q['explanation'].strip()
    # 清洗提取残留
    orig = re.sub(r'历年.{0,12}相关试题[：:]', '', orig)
    orig = orig.replace('●', '- ')
    orig = re.sub(r'^解\s*析\s*[：:]\s*', '', orig)
    orig = re.sub(r'本[题问].{0,6}(选择|考查)', r'本题\1', orig)
    orig = re.sub(r'\s{2,}', ' ', orig).strip()
    if len(orig) >= 15:
        return f'{src}\n\n{orig}'
    return (f'{src}\n\n**答案**：{ans}\n\n本题解析从略，'
            f'可点击「AI 深度讲解」获取针对本题的通俗讲解与举一反三练习。')

def ts_str(s):
    """转成 TS 单引号字符串字面量"""
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n') + "'"

def main():
    data = json.load(open(os.path.join(HERE, 'merged.json'), encoding='utf-8'))
    lines = [
        "import type { Question } from '../types'",
        '',
        '/** 历年上午真题（2020—2024，来源：用户提供的软考资源包，经脚本提取与校验） */',
        'export const examQuestions: Question[] = [',
    ]
    counters = {}
    for q in sorted(data, key=lambda x: (x['exam'], x['no'])):
        mid = q['moduleId']
        counters[mid] = counters.get(mid, 0) + 1
        exam_tag = q['exam'].replace('-', '')
        qid = f'ex{exam_tag}-{q["no"]:02d}'
        chapter = pick_chapter(q)
        explanation = build_explanation(q)
        opts = ',\n      '.join(ts_str(o) for o in q['options'])
        lines.append('  {')
        lines.append(f'    id: {ts_str(qid)},')
        lines.append(f"    moduleId: {ts_str(mid)},")
        lines.append(f'    chapter: {ts_str(chapter)},')
        lines.append(f'    stem: {ts_str(q["stem"])},')
        lines.append(f'    options: [\n      {opts},\n    ],')
        lines.append(f'    answer: {q["answer"]},')
        lines.append(f'    explanation: {ts_str(explanation)},')
        lines.append(f'    difficulty: {guess_difficulty(q)},')
        lines.append('  },')
    lines.append(']')
    out = os.path.join(PROJ, 'src', 'data', 'questions', 'exam.ts')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print('生成:', out)
    print('题数分布:', counters, '总计', len(data))

if __name__ == '__main__':
    main()
